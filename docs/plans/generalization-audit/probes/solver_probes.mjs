// Equilibrium-solver residuals and step cost on the built WASM engine.
import { readFileSync } from 'node:fs';
import path from 'node:path';
const dir = '/Users/carlliu/reaction-chamber/web/src/wasm/engine';
const eng = await import(path.join(dir, 'reaction_chamber_engine.js'));
eng.initSync({ module: readFileSync(path.join(dir, 'reaction_chamber_engine_bg.wasm')) });
eng.init_engine();
const J = (x) => (typeof x === 'string' ? JSON.parse(x) : x);
const mk = (T) => eng.vessel_new(JSON.stringify({ type: 'beaker-250', capacity_ml: 250, glass_mass_g: 110, inner_radius_cm: 3.5, temperature_k: T, room_k: T }));
const dose = (h, d) => eng.vessel_dose(h, JSON.stringify(d));
const snap = (h) => J(eng.vessel_snapshot(h));
const imp = (r) => J(eng.import_compound(JSON.stringify(r)));
const c = (s, id) => (s.species.find((x) => x.id === id) || {}).conc_m ?? 0;
const L = Math.log10;

// Residuals of the carbonate / ammonia / water equilibria in a busy mixture
imp({ id: 'x_Na2CO3', name: 'Na2CO3', formula: 'CNa2O3', state: 'liquid', molarity: 0.5 });
imp({ id: 'x_NH4Cl', name: 'NH4Cl', formula: 'ClH4N', state: 'liquid', molarity: 1.0 });
imp({ id: 'x_Na3PO4', name: 'Na3PO4', formula: 'Na3O4P', state: 'liquid', molarity: 0.2 });
imp({ id: 'x_CaCl2', name: 'CaCl2', formula: 'CaCl2', state: 'liquid', molarity: 0.5 });
const h = mk(298.15);
dose(h, { reagent_id: 'water', volume_ml: 50 });
dose(h, { reagent_id: 'x_Na2CO3', volume_ml: 20 });
dose(h, { reagent_id: 'x_NH4Cl', volume_ml: 20 });
dose(h, { reagent_id: 'x_Na3PO4', volume_ml: 10 });
dose(h, { reagent_id: 'x_CaCl2', volume_ml: 10 });
dose(h, { reagent_id: 'cuso4_0_1m', volume_ml: 10 });
dose(h, { reagent_id: 'agno3_0_1m', volume_ml: 5 });
dose(h, { reagent_id: 'ch3cooh_5pct', volume_ml: 10 });
let s = snap(h);
const show = (s, tag) => {
  const H = c(s, 'H+'), OH = c(s, 'OH-');
  console.log(`${tag}: T=${s.temperature_k.toFixed(2)} pH=${s.ph?.toFixed(3)} I=${s.ionic_strength?.toFixed(3)}`);
  console.log(`  log Kw resid = ${(L(H * OH) + 14).toFixed(4)}`);
  if (c(s, 'HCO3-') > 0 && c(s, 'CO2(aq)') > 0) console.log(`  carbonic1 resid = ${(L(H * c(s, 'HCO3-') / c(s, 'CO2(aq)')) + 6.35).toFixed(4)}`);
  if (c(s, 'CO3-2') > 0) console.log(`  bicarb2 resid = ${(L(H * c(s, 'CO3-2') / c(s, 'HCO3-')) + 10.33).toFixed(4)}`);
  if (c(s, 'NH3') > 0) console.log(`  NH3 resid = ${(L(c(s, 'NH4+') * OH / c(s, 'NH3')) + 4.75).toFixed(4)}`);
  console.log('  species count', s.species.length, 'solids', s.solids.map((x) => x.species).join(','));
  console.log('  reactions in log:', [...new Set(s.reactions.map((r) => r.id))].join(','));
};
show(s, 'after doses');
let t0 = performance.now();
const N = 200;
for (let i = 0; i < N; i++) eng.vessel_step(h, 0.05);
let t1 = performance.now();
s = snap(h);
show(s, 'after 10 s');
console.log(`vessel_step cost: ${((t1 - t0) / N).toFixed(3)} ms/step (busy mixture)`);
const h2 = mk(298.15);
dose(h2, { reagent_id: 'water', volume_ml: 100 });
t0 = performance.now();
for (let i = 0; i < N; i++) eng.vessel_step(h2, 0.05);
t1 = performance.now();
console.log(`vessel_step cost: ${((t1 - t0) / N).toFixed(3)} ms/step (pure water)`);
t0 = performance.now();
for (let i = 0; i < 20; i++) eng.vessel_snapshot(h);
t1 = performance.now();
console.log(`vessel_snapshot cost: ${((t1 - t0) / 20).toFixed(3)} ms`);
t0 = performance.now();
for (let i = 0; i < 20; i++) dose(h, { reagent_id: 'water', volume_ml: 0.1 });
t1 = performance.now();
console.log(`small dose (settle_after_addition) cost: ${((t1 - t0) / 20).toFixed(3)} ms`);
