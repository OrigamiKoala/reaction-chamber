/// Mass of the most abundant isotope, u.
pub fn mono_mass(el: &str) -> Option<f64> {
    let iso = isotopes(el)?;
    iso.iter().max_by(|a, b| a.1.partial_cmp(&b.1).unwrap()).map(|i| i.0)
}

/// Abundance-weighted mean mass, u.
pub fn avg_mass(el: &str) -> Option<f64> {
    let iso = isotopes(el)?;
    let tot: f64 = iso.iter().map(|i| i.1).sum();
    Some(iso.iter().map(|i| i.0 * i.1).sum::<f64>() / tot)
}

/// One line of an isotopic distribution at unit mass resolution.
#[derive(Clone, Debug)]
pub struct IsoLine {
    /// Nominal mass (integer) of the line, u.
    pub nominal: i32,
    /// Abundance-weighted exact mass of everything that falls on the line, u.
    pub mass: f64,
    /// Probability (the lines sum to 1).
    pub p: f64,
}

/// Isotopic distribution of a composition at unit resolution (lines binned by nominal mass; lines below `cutoff` dropped).
/// `counts` are (element, atoms). None if an element has no isotope data.
pub fn distribution(counts: &[(String, u32)], cutoff: f64) -> Option<Vec<IsoLine>> {
    let mut dist: Vec<IsoLine> = vec![IsoLine { nominal: 0, mass: 0.0, p: 1.0 }];
    for (el, n) in counts {
        let iso = isotopes(el)?;
        // exponentiation by repeated squaring on the (small) element polynomial
        let mut base: Vec<IsoLine> = iso.iter().map(|&(m, a)| IsoLine { nominal: m.round() as i32, mass: m, p: a }).collect();
        base = merge(base);
        let mut result: Vec<IsoLine> = vec![IsoLine { nominal: 0, mass: 0.0, p: 1.0 }];
        let mut e = *n;
        while e > 0 {
            if e & 1 == 1 {
                result = convolve(&result, &base, cutoff * 1e-3);
            }
            e >>= 1;
            if e > 0 {
                base = convolve(&base, &base, cutoff * 1e-3);
            }
        }
        dist = convolve(&dist, &result, cutoff * 1e-3);
    }
    let tot: f64 = dist.iter().map(|l| l.p).sum();
    let mut out: Vec<IsoLine> = dist.into_iter().map(|l| IsoLine { p: l.p / tot, ..l }).filter(|l| l.p >= cutoff).collect();
    out.sort_by_key(|l| l.nominal);
    Some(out)
}

fn merge(mut v: Vec<IsoLine>) -> Vec<IsoLine> {
    v.sort_by_key(|l| l.nominal);
    let mut out: Vec<IsoLine> = Vec::new();
    for l in v {
        match out.last_mut() {
            Some(last) if last.nominal == l.nominal => {
                let p = last.p + l.p;
                last.mass = (last.mass * last.p + l.mass * l.p) / p;
                last.p = p;
            }
            _ => out.push(l),
        }
    }
    out
}

fn convolve(a: &[IsoLine], b: &[IsoLine], prune: f64) -> Vec<IsoLine> {
    let mut out: Vec<IsoLine> = Vec::with_capacity(a.len() * b.len());
    for x in a {
        for y in b {
            let p = x.p * y.p;
            if p < prune {
                continue;
            }
            out.push(IsoLine { nominal: x.nominal + y.nominal, mass: x.mass + y.mass, p });
        }
    }
    merge(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn comp(s: &[(&str, u32)]) -> Vec<(String, u32)> {
        s.iter().map(|(e, n)| (e.to_string(), *n)).collect()
    }

    #[test]
    fn chlorine_pattern() {
        let d = distribution(&comp(&[("Cl", 1)]), 1e-6).unwrap();
        assert_eq!(d.len(), 2);
        assert!((d[1].p / d[0].p - 0.3199).abs() < 0.01);
        let d = distribution(&comp(&[("C", 1), ("H", 1), ("Cl", 3)]), 1e-6).unwrap();
        // CHCl3: M : M+2 : M+4 : M+6 ~ 100 : 96 : 31 : 3.3
        let m = d[0].p;
        assert!((d[2].p / m - 0.958).abs() < 0.03, "{:?}", d);
        assert!((d[4].p / m - 0.306).abs() < 0.03);
    }

    #[test]
    fn benzene_m_plus_one() {
        let d = distribution(&comp(&[("C", 6), ("H", 6)]), 1e-6).unwrap();
        assert!((d[1].p / d[0].p - 0.0676).abs() < 0.003);
    }
}
